/**
 * العددُ في العربيةِ ليس زينةً على السطر، «3 يوم» جملةٌ ناقصة: «يوم» مفردٌ
 * و«أيام» جمعٌ تكسيرٌ لا مفردُه بالزيادة. ومَن كتب «5 سجل» جَرَدَ العددَ من
 * حاله، فيصحّ معناه ويخطئ لفظه، فيقف القارئُ عند اللفظ قبل أن يوصل إلى
 * الرقم.
 *
 * فوجهُ العددٍ يُمرَّرُ من موضعه ولا يُخمَّن في المستدعي: «أيام» جمعٌ تكسير،
 * و«ساعات» كذلك، بينما جمعُ «موظفٍ» تكسيرٌ تامٌ فيقول «موظفون». ومَن ترك
 * القاعدةَ تخميناً كتب «3 موظفات» أو «3 ساعة»، وكلاهما خطأٌ يوقف القراءة.
 */

import { formatNumber } from './format';

/**
 * صيغة العدد: واحدٌ ومثنًى وجمع.
 *
 * ثلاثةٌ وعشرةٌ يقعان في «دقائق»، والخمسةُ والعشرون في «دقيقة». من كتب
 * «دقيقتان» بجوار الرقم 2 كتب جملةً عربيةً جُرّدت من العدد، فيقرأها
 * العربي «دقيقتين» فيبحث عن رقمٍ ليس في السطر.
 */
export function pluralize(
  count: number,
  singular: string,
  dual: string,
  plural: string,
): string {
  if (count === 1) return singular;
  if (count === 2) return dual;
  if (count >= 3 && count <= 10) return plural;
  return singular;
}

/**
 * «5 سجلات» — العددُ متبوعاً بمسمّاه بالوجه الذي يطلبُه العدد.
 *
 * والرقمُ يمرُّ على `formatNumber` قبل ألصاقه، فتكتب الآلافُ «1,200»
 * مفصولةً كما في كلِّ موضعٍ آخر من الشاشة، لا متلاصقةً كتسعِ خانات.
 */
export function counted(
  count: number,
  singular: string,
  dual: string,
  plural: string,
): string {
  return `${formatNumber(count)} ${pluralize(count, singular, dual, plural)}`;
}