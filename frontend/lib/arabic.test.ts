import { describe, it, expect } from 'vitest';
import { pluralize, counted } from './arabic';

describe('pluralize', () => {
  it('يفرّق الواحد والمثنى والجمع', () => {
    expect(pluralize(1, 'يوم', 'يومان', 'أيام')).toBe('يوم');
    expect(pluralize(2, 'يوم', 'يومان', 'أيام')).toBe('يومان');
    expect(pluralize(5, 'يوم', 'يومان', 'أيام')).toBe('أيام');
    expect(pluralize(11, 'يوم', 'يومان', 'أيام')).toBe('يوم');
  });

  it('لا يخمّن وجهاً لم يُمرَّر: تكسيرٌ في وصفٍ وجمعٌ تامٌ في آخر', () => {
    // جمعُ «موظف» تكسيرٌ تامٌ لا سالم، فلو خمّن المستدعي لـ«سالم»
    // لكتب «3 موظفات» موضعَ «3 موظفون».
    expect(pluralize(3, 'موظف', 'موظفان', 'موظفون')).toBe('موظفون');
    expect(pluralize(3, 'ساعة', 'ساعتان', 'ساعات')).toBe('ساعات');
  });
});

describe('counted', () => {
  it('يجمع العددَ بمسمّاه بالوجه الصحيح', () => {
    expect(counted(1, 'سجل', 'سجلّان', 'سجلات')).toBe('1 سجل');
    expect(counted(3, 'سجل', 'سجلّان', 'سجلات')).toBe('3 سجلات');
    expect(counted(12, 'سجل', 'سجلّان', 'سجلات')).toBe('12 سجل');
  });

  it('يفصل الآلاف، فلا تلتصق التسعُ خاناتٍ في سطرٍ ضيّق', () => {
    expect(counted(1200, 'يوم', 'يومان', 'أيام')).toBe('1,200 يوم');
    expect(counted(1000, 'سجل', 'سجلّان', 'سجلات')).toBe('1,000 سجل');
  });

  it('يعيد المفردَ تحت العشرةِ وفوقه، فلا يقع بين حدَّي العدد خطأ', () => {
    expect(counted(10, 'دقيقة', 'دقيقتان', 'دقائق')).toBe('10 دقائق');
    expect(counted(11, 'دقيقة', 'دقيقتان', 'دقائق')).toBe('11 دقيقة');
    expect(counted(99, 'دقيقة', 'دقيقتان', 'دقائق')).toBe('99 دقيقة');
  });

  it('لا يفصلُ الأرقامَ الصغيرة، فيبقى الرقمُ متسلسلَ الحفظ', () => {
    expect(counted(0, 'وردية', 'ورديتان', 'ورديات')).toBe('0 وردية');
    expect(counted(9, 'وردية', 'ورديتان', 'ورديات')).toBe('9 ورديات');
  });

  it('يفردُ الصفرَ على مذهب العربية في «صفرِ دقيقة» و«صفرِ سجل»', () => {
    // الصفرُ يقع على المفرد لا على الجمع في هذه الأسماء، فلا يستقيم أن
    // يُقاس بمقياس العشرةِ فيُكتب «0 ورديات». والقاعدةُ موثّقةٌ في
    // `pluralize`: وهو خارجُ الواحدِ والمثنى والثلاثةِ إلى العشرة،
    // فيعود إلى المفرد.
    expect(counted(0, 'سجل', 'سجلّان', 'سجلات')).toBe('0 سجل');
    expect(counted(0, 'ساعة', 'ساعتان', 'ساعات')).toBe('0 ساعة');
  });
});