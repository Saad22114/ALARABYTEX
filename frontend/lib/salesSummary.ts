/**
 * لوحةُ مبيعاتِ اليوم: أرقامٌ يقرؤها صاحبُ المحلّ كلَّ صباح، فمقاماتُها جزءٌ
 * من معناها لا زينةٌ عليه.
 *
 * وأخطرُ ما فيها «متوسطُ اليوم»، فهو مجموعُ المبيعاتِ على عددِ الأيامِ التي
 * فيها مبيعاتٌ فعلاً، لا على أيامِ الفترةِ كلِّها. ويومٌ لم يُبع فيه شيءٌ ليس
 * في المقام، لأنه لم يدخل في المجموع أصلاً. فالرقمُ صحيحٌ في الحسابِ ومربكٌ
 * في القراءة، إذ يظنّه القارئُ قِسمةً على كلِّ الأيامِ فيجده أكبرَ ممّا
 * يتوقّع، ثمّ يظنّ أنّ الرقمَ في واحدةٍ من العددين خطأ.
 */

import { counted } from './arabic';

/** الحقولُ التي تردُ في ردّ `/sales/summary/`. */
export interface SalesSummaryTotals {
  total_sales: number;
  cash: number;
  transfer: number;
  card: number;
  other: number;
  sales_count: number;
  days_count: number;
}

/**
 * كلُّ ما ليس نقداً: التحويلُ والبطاقةُ و«أخرى».
 *
 * والبطاقةُ كانت تجمع الأولين وتترك الثالث، فتصير البطاقاتُ في صفٍّ لا
 * تجمع إلى الإجمالي. و«أخرى» ليست صفراً مضموناً: بذرُ العرض يحسبها فائضاً
 * (`total - cash - transfer - card`)، والواجهةُ البرمجية تكتبها. ولئن كانت
 * صفراً في هذا المحلّ فذلك لا يحقّ للبطاقاتِ أن تُسقط خانةً من التقويم
 * صامتةً، إذ يبقى على القارئ أن يجمع الأعمدةَ بنفسه فيرى ما نقص.
 */
export function nonCashTotal(summary: SalesSummaryTotals): number {
  return (summary.transfer || 0) + (summary.card || 0) + (summary.other || 0);
}

/**
 * المتوسّطُ على أيامِ البيعِ لا على أيامِ التقويم. ويُرجَع صفرٌ لا صفرٌ
 * قابلٌ للقسمة، فالفترةُ بلا مبيعاتٍ تقسمُ على صفرٍ فتُعطي «NaN» فيحمل
 * النصُّ «NaN» مكانَ رقم.
 */
export function averagePerSellingDay(
  totalSales: number,
  sellingDays: number,
): number {
  return sellingDays > 0 ? totalSales / sellingDays : 0;
}

/**
 * «12 سجل في 5 أيام» — تحتَ إجمالي المبيعات، فيقرأ العددان معاً لأنّ
 * أحدهما بلا الآخر لا يعني شيئاً: خمسةُ سجلاتٍ في يومٍ واحدٍ شيءٌ، وفي
 * خمسةِ أيامٍ شيءٌ آخر.
 */
export function recordsInDaysNote(records: number, days: number): string {
  return `${counted(records, 'سجل', 'سجلّان', 'سجلات')} في ${
    counted(days, 'يوم', 'يومان', 'أيام')
  }`;
}

/**
 * «على 5 أيام بيعٍ» — تحتَ المتوسّط.
 *
 * فالسطرُ يقولُ كم يوماً قُسِم المجموعُ عليه. وبلا هذا السطر يبقى الرقمُ
 * مجهولَ المقام، فيقرأه القارئُ على أنّه متوسّطُ كلِّ أيامِ الفترة، فيحسب
 * الفارقَ خطأً في بطاقته ويظنّ البياناتَ هي التي تغيّرت.
 */
export function sellingDaysNote(days: number): string {
  return `على ${counted(days, 'يوم بيع', 'يومَي بيع', 'أيام بيع')}ٍ`;
}